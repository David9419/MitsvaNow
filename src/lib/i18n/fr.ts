/** Même forme que le dictionnaire français, mais avec n'importe quels textes. */
type Elargir<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : T extends readonly (infer U)[]
      ? Elargir<U>[]
      : { [K in keyof T]: Elargir<T[K]> }

export type Dico = Elargir<typeof fr>
